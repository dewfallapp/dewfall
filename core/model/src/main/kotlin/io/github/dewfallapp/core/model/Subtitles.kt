package io.github.dewfallapp.core.model

import kotlin.time.Duration

/**
 * One of a video's subtitle tracks. Read its lines soon after listing the tracks, because the link
 * stops working after some time, like a stream link: about 7 hours in a check on November 18, 2026.
 * The URL is user data, so never log it. See ADR 0007.
 */
data class SubtitleTrack(
    val videoId: VideoId,
    /**
     * The language as a BCP 47 tag, such as en, pt-BR or he, or und if YouTube's code for it isn't
     * one.
     */
    val languageTag: String,
    /** True if YouTube generated the subtitles from speech, false if a person wrote them. */
    val isAutoGenerated: Boolean,
    /**
     * The link that the YouTube layer reads the track's lines from. Pass the track back as it is.
     */
    val url: String,
)

/**
 * One line of subtitles, with the times that YouTube gives it. Lines can overlap, when two are on
 * screen at once. In an auto-generated track they overlap by design: YouTube shows two lines at
 * once, so each line disappears when the line after the next one appears. Its text is user data, so
 * never log it. See ADR 0007.
 */
data class SubtitleLine(
    /** When the line appears, from the start of the video. */
    val start: Duration,
    /** When the line disappears, from the start of the video. Always after [start]. */
    val end: Duration,
    /**
     * The line as plain text, never empty. It can span more than one line on screen, with a line
     * break between them.
     */
    val text: String,
)
