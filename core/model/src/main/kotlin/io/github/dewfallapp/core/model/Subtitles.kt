package io.github.dewfallapp.core.model

import kotlin.time.Duration

/**
 * One of a video's subtitle tracks. Read its lines soon after listing the tracks, because the link
 * may stop working after some time, like a stream link. The URL is user data, so never log it. See
 * ADR 0007.
 */
data class SubtitleTrack(
    val videoId: VideoId,
    /** The language as a BCP 47 tag, such as en or pt-BR. */
    val languageTag: String,
    /** True if YouTube generated the subtitles from speech, false if a person wrote them. */
    val isAutoGenerated: Boolean,
    val url: String,
)

/** One line of subtitles. Its text is user data, so never log it. See ADR 0007. */
data class SubtitleLine(
    /** When the line appears, from the start of the video. */
    val start: Duration,
    /** When the line disappears, from the start of the video. */
    val end: Duration,
    /** The line as plain text. It can span more than one line on screen. */
    val text: String,
)
