import java.io.IOException
import java.net.HttpURLConnection.HTTP_FORBIDDEN
import java.net.HttpURLConnection.HTTP_GONE
import java.net.HttpURLConnection.HTTP_NOT_FOUND
import java.net.HttpURLConnection.HTTP_OK
import okhttp3.HttpUrl.Companion.toHttpUrlOrNull
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.downloader.Response
import org.schabi.newpipe.extractor.stream.StreamExtractor

/**
 * The statuses with which YouTube refuses a subtitle link that no longer works. An expired link, a
 * link whose signature doesn't match, and a link for another video all got 404 in a check on
 * November 18, 2026. 403 with an HTML body is Google's block page, which NewPipeDownloader turns
 * into a refusal by YouTube before it gets here.
 */
private val LINK_REFUSED_STATUSES = setOf(HTTP_FORBIDDEN, HTTP_NOT_FOUND, HTTP_GONE)

/** The first and last status of a server error, which can pass when the call is made again. */
private const val FIRST_SERVER_ERROR = 500
private const val LAST_SERVER_ERROR = 599

/** The query parameter of a subtitle link that says how YouTube made the track. */
private const val VARIANT = "variant"

/** The variant of the auto-generated tracks that YouTube makes from AI-dubbed audio tracks. */
private const val DUBBED_AUDIO_VARIANT = "timing-optimized"

/**
 * Thrown when YouTube refuses a subtitle link, such as one that expired. It maps to UNAVAILABLE,
 * and the caller lists the tracks again for a link that works.
 */
internal class SubtitleLinkRefusedException :
    Exception("YouTube refused the link of a subtitle track")

/**
 * Thrown when YouTube answers a subtitle link with a server error. It is an IOException, so it maps
 * to NETWORK, which tells a caller to try again later.
 */
internal class YouTubeServerErrorException : IOException("YouTube answered with a server error")

/**
 * Reads a video's subtitle tracks from its fetched page, and a track's lines from its link. See
 * docs/architecture.md#subtitles.
 */
internal class NewPipeSubtitles(private val calls: NewPipeCalls, logger: Logger) :
    SubtitlesRemoteDataSource {
    private val log = logger.withTag(LOG_AREA)

    override suspend fun subtitleTracks(videoId: VideoId): YouTubeResult<List<SubtitleTrack>> =
        calls.run(YouTubeCall.SUBTITLE_TRACKS) { settings ->
            val extractor = fetchedStreamExtractor(videoId, settings)
            val skipped = SkippedParts(YouTubeCall.SUBTITLE_TRACKS)
            val tracks = subtitleTracksOf(videoId, extractor, skipped)
            skipped.warnIfAny(log)
            tracks
        }

    override suspend fun subtitleLines(track: SubtitleTrack): YouTubeResult<List<SubtitleLine>> =
        // The download calls none of NewPipeExtractor's code that touches its static state, so it
        // doesn't wait for NewPipeExtractor's lock. Its request still goes through the downloader
        // and its host checks.
        calls.runDownload(YouTubeCall.SUBTITLE_LINES) { downloader ->
            val answer = downloader.get(track.url, REQUEST_LOCALIZATION)
            val skipped = SkippedParts(YouTubeCall.SUBTITLE_LINES)
            val lines = subtitleLinesOf(answer, skipped)
            skipped.warnIfAny(log)
            lines
        }
}

/**
 * The subtitle tracks of the video with [videoId] that [extractor] fetched, in YouTube's order,
 * each with its TTML link. NewPipeExtractor lists only the tracks that YouTube has, never its
 * machine translations. The auto-generated tracks that YouTube makes from AI-dubbed audio are
 * machine translations too, so they are left out. A language code that isn't a BCP 47 tag becomes
 * [UNDETERMINED_LANGUAGE] and counts as a parse error in [skipped].
 */
internal fun subtitleTracksOf(
    videoId: VideoId,
    extractor: StreamExtractor,
    skipped: SkippedParts,
): List<SubtitleTrack> {
    val tracks = mutableListOf<SubtitleTrack>()
    for (stream in extractor.getSubtitles(MediaFormat.TTML)) {
        val link = stream.content
        if (stream.isAutoGenerated && isMadeFromDubbedAudio(link)) continue
        val languageTag = languageTagOf(stream.languageTag)
        if (languageTag == null) skipped.addParseErrors(1)
        tracks +=
            SubtitleTrack(
                videoId = videoId,
                languageTag = languageTag ?: UNDETERMINED_LANGUAGE,
                isAutoGenerated = stream.isAutoGenerated,
                url = link,
            )
    }
    return tracks
}

/**
 * Whether [link], an auto-generated track's link, names a track that YouTube made from one of the
 * video's AI-dubbed audio tracks. YouTube doesn't document the parameter. In a check on November
 * 18, 2026, each of three NASA videos had 20 such tracks, one for each dubbed audio track, while
 * the track of the original speech had another variant or none.
 */
private fun isMadeFromDubbedAudio(link: String): Boolean =
    link.toHttpUrlOrNull()?.queryParameter(VARIANT) == DUBBED_AUDIO_VARIANT

/**
 * The lines in [answer], YouTube's answer to a track's link. A refused link throws
 * [SubtitleLinkRefusedException], a server error [YouTubeServerErrorException], and any other
 * status, or an answer that isn't a TTML file, [NotSubtitlesException].
 */
internal fun subtitleLinesOf(answer: Response, skipped: SkippedParts): List<SubtitleLine> =
    when (answer.responseCode()) {
        HTTP_OK -> ttmlLinesOf(answer.responseBody(), skipped)
        in LINK_REFUSED_STATUSES -> throw SubtitleLinkRefusedException()
        in FIRST_SERVER_ERROR..LAST_SERVER_ERROR -> throw YouTubeServerErrorException()
        else -> throw NotSubtitlesException()
    }
