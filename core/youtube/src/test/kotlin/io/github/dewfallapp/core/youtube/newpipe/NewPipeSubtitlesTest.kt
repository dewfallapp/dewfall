/**
 * A marker that a test puts in a track's link and in its lines, so that it can check that no log
 * line holds either.
 */
private const val MARKER = "MarkerFromTheTest"

/**
 * A subtitle link as NewPipeExtractor builds one, for the track in [lang], with [extra] at the end.
 */
private fun timedTextLink(lang: String, extra: String = "") =
    "https://www.youtube.com/api/timedtext?v=$VIDEO_A&ei=$MARKER&caps=asr&lang=$lang$extra&fmt=ttml"

/** A TTML file with one line, as YouTube writes it, whose text holds [MARKER]. */
private const val ONE_LINE_TTML =
    """<?xml version="1.0" encoding="utf-8" ?><tt xmlns="http://www.w3.org/ns/ttml"><body><div>""" +
        """<p begin="00:00:01.000" end="00:00:02.500">said $MARKER here</p>""" +
        """<p begin="00:00:03.000">no end, so it is left out</p></div></body></tt>"""

/** The start of the error page that YouTube sent with 404 for an expired subtitle link. */
private const val ERROR_PAGE =
    "<!DOCTYPE html>\n<html lang=en>\n  <title>Error 404 (Not Found)!!1</title>"

class NewPipeSubtitlesTest {
    private val lines = mutableListOf<String>()
    private val sent = mutableListOf<Request>()
    private val skipped = SkippedParts(YouTubeCall.SUBTITLE_TRACKS)

    @BeforeTest
    fun setUp() {
        setUpNewPipeWithoutRequests()
    }

    @Test
    fun `tracks come in YouTube's order, each with its TTML link`() {
        val asked = mutableListOf<MediaFormat>()
        val page =
            FakeStreamPage(
                subtitles = { format ->
                    asked += format
                    listOf(
                        subtitlesStream("en", isAutoGenerated = false),
                        subtitlesStream("de", isAutoGenerated = false),
                        subtitlesStream("en", isAutoGenerated = true),
                    )
                }
            )

        val tracks = subtitleTracksOf(VideoId(VIDEO_A), page, skipped)

        assertEquals(listOf(MediaFormat.TTML), asked)
        assertEquals(
            listOf(
                SubtitleTrack(VideoId(VIDEO_A), "en", isAutoGenerated = false, timedTextLink("en")),
                SubtitleTrack(VideoId(VIDEO_A), "de", isAutoGenerated = false, timedTextLink("de")),
                SubtitleTrack(VideoId(VIDEO_A), "en", isAutoGenerated = true, timedTextLink("en")),
            ),
            tracks,
        )
    }

    @Test
    fun `auto-generated tracks made from dubbed audio are left out, and the others kept`() {
        val dubbed = "&kind=asr&variant=timing-optimized"
        val page =
            FakeStreamPage(
                subtitles = {
                    listOf(
                        subtitlesStream("ar", isAutoGenerated = true, extra = dubbed),
                        subtitlesStream("en", isAutoGenerated = false),
                        subtitlesStream(
                            "en",
                            isAutoGenerated = true,
                            extra = "&kind=asr&variant=gemini",
                        ),
                        subtitlesStream("hi", isAutoGenerated = true, extra = dubbed),
                        subtitlesStream("fr", isAutoGenerated = true, extra = "&kind=asr"),
                        // Only an auto-generated track can be a machine translation of dubbed
                        // audio, so a written track keeps whatever variant its link names.
                        subtitlesStream("de", isAutoGenerated = false, extra = dubbed),
                    )
                }
            )

        val tracks = subtitleTracksOf(VideoId(VIDEO_A), page, skipped)

        assertEquals(
            listOf("en" to false, "en" to true, "fr" to true, "de" to false),
            tracks.map { it.languageTag to it.isAutoGenerated },
        )
        warnIfAny()
        assertEquals(emptyList(), lines)
    }

    @Test
    fun `YouTube's code for Hebrew becomes its BCP 47 tag`() {
        val page =
            FakeStreamPage(subtitles = { listOf(subtitlesStream("iw", isAutoGenerated = false)) })

        val tracks = subtitleTracksOf(VideoId(VIDEO_A), page, skipped)

        assertEquals(listOf("he"), tracks.map { it.languageTag })
        assertEquals(listOf(timedTextLink("iw")), tracks.map { it.url })
    }

    @Test
    fun `a code that isn't a tag keeps the track as und, and counts as a parse error`() {
        val page =
            FakeStreamPage(
                subtitles = { listOf(subtitlesStream("en_US", isAutoGenerated = false)) }
            )

        val tracks = subtitleTracksOf(VideoId(VIDEO_A), page, skipped)

        assertEquals(listOf(UNDETERMINED_LANGUAGE), tracks.map { it.languageTag })
        warnIfAny()
        assertEquals(
            listOf(
                "WARN Dewfall.YouTube YouTube answer read in part call=SUBTITLE_TRACKS dropped=0 " +
                    "parseErrors=1"
            ),
            lines,
        )
    }

    @Test
    fun `a video with no tracks has none`() {
        assertEquals(emptyList(), subtitleTracksOf(VideoId(VIDEO_A), FakeStreamPage(), skipped))
    }

    @Test
    fun `reading a track sends one GET for its link, in British English, and reads its lines`() =
        runTest {
            val subtitles =
                subtitlesAnswering(testScheduler) { answer(it, 200, ONE_LINE_TTML, XML) }

            val result = subtitles.subtitleLines(track())

            assertEquals(
                YouTubeResult.Success(
                    listOf(SubtitleLine(1.seconds, 2.5.seconds, "said $MARKER here"))
                ),
                result,
            )
            val request = sent.single()
            assertEquals("GET", request.method)
            assertEquals(timedTextLink("en"), request.url.toString())
            assertEquals("en-GB, en;q=0.9", request.header("Accept-Language"))
            assertEquals(
                listOf(
                    "WARN Dewfall.YouTube YouTube answer read in part call=SUBTITLE_LINES " +
                        "dropped=1 parseErrors=0"
                ),
                lines,
            )
        }

    @Test
    fun `a link that YouTube refuses is UNAVAILABLE, so the caller lists the tracks again`() =
        runTest {
            for ((status, contentType) in listOf(404 to HTML, 410 to HTML, 403 to PLAIN_TEXT)) {
                val subtitles =
                    subtitlesAnswering(testScheduler) {
                        answer(it, status, ERROR_PAGE, contentType)
                    }

                assertEquals(
                    YouTubeResult.Failure(YouTubeError.UNAVAILABLE),
                    subtitles.subtitleLines(track()),
                    "HTTP $status",
                )
            }
        }

    @Test
    fun `Google's block page and too many requests are BLOCKED`() = runTest {
        for ((status, contentType) in listOf(403 to HTML, 429 to HTML)) {
            val subtitles =
                subtitlesAnswering(testScheduler) {
                    answer(it, status, "<html>Sorry...</html>", contentType)
                }

            assertEquals(
                YouTubeResult.Failure(YouTubeError.BLOCKED),
                subtitles.subtitleLines(track()),
                "HTTP $status",
            )
        }
    }

    @Test
    fun `a server error is NETWORK, so the caller tries again later`() = runTest {
        for (status in listOf(500, 503)) {
            val subtitles = subtitlesAnswering(testScheduler) { answer(it, status, "", HTML) }

            assertEquals(
                YouTubeResult.Failure(YouTubeError.NETWORK),
                subtitles.subtitleLines(track()),
                "HTTP $status",
            )
        }
    }

    @Test
    fun `any other status, and an answer that isn't a TTML file, are BROKEN`() = runTest {
        val answers =
            listOf(
                Triple(400, ERROR_PAGE, HTML),
                Triple(302, "", HTML),
                // YouTube's answer to a link without its signature, or for a missing language.
                Triple(200, "", HTML),
                Triple(200, ERROR_PAGE, HTML),
                Triple(200, """{"events":[]}""", "application/json"),
            )
        for ((status, body, contentType) in answers) {
            val subtitles =
                subtitlesAnswering(testScheduler) {
                    answer(it, status, body, contentType)
                }

            assertEquals(
                YouTubeResult.Failure(YouTubeError.BROKEN),
                subtitles.subtitleLines(track()),
                "HTTP $status with $contentType",
            )
        }
    }

    @Test
    fun `a link to another host is BROKEN, and nothing is sent`() = runTest {
        val subtitles = subtitlesAnswering(testScheduler) { answer(it, 200, ONE_LINE_TTML, XML) }

        val result =
            subtitles.subtitleLines(track(url = "https://example.com/api/timedtext?lang=en"))

        assertEquals(YouTubeResult.Failure(YouTubeError.BROKEN), result)
        assertEquals(emptyList(), sent)
    }

    @Test
    fun `log lines hold neither the track's link nor its text`() = runTest {
        val textLines = mutableListOf<String>()
        val logger =
            Logger(
                { _, _, text -> textLines += text },
                LogLevel.DEBUG,
            )
        val readInPart =
            subtitlesAnswering(testScheduler, logger) { answer(it, 200, ONE_LINE_TTML, XML) }
        val refused =
            subtitlesAnswering(testScheduler, logger) { answer(it, 404, ERROR_PAGE, HTML) }

        readInPart.subtitleLines(track())
        refused.subtitleLines(track())

        assertEquals(2, textLines.size)
        assertTrue(
            textLines.last().startsWith("YouTube call failed call=SUBTITLE_LINES error=UNAVAILABLE")
        )
        assertFalse(textLines.any { MARKER in it })
    }

    private fun warnIfAny() {
        skipped.warnIfAny(recordingLogger(lines).withTag(LOG_AREA))
    }

    /** A track of [VIDEO_A] in English, whose link is [url]. */
    private fun track(url: String = timedTextLink("en")) =
        SubtitleTrack(VideoId(VIDEO_A), "en", isAutoGenerated = false, url = url)

    /**
     * The subtitles of a layer whose HTTP client answers every request with [answer], through the
     * layer's own downloader and calls, which log to [logger].
     */
    private fun subtitlesAnswering(
        scheduler: TestCoroutineScheduler,
        logger: Logger = recordingLogger(lines),
        answer: (Request) -> Response,
    ): NewPipeSubtitles {
        val client =
            OkHttpClient.Builder()
                .addInterceptor { chain ->
                    sent += chain.request()
                    answer(chain.request())
                }
                .build()
        val calls =
            NewPipeCalls(NewPipeDownloader(client), logger, StandardTestDispatcher(scheduler))
        return NewPipeSubtitles(calls, logger)
    }

    private fun answer(request: Request, code: Int, body: String, contentType: String): Response =
        Response.Builder()
            .request(request)
            .protocol(Protocol.HTTP_1_1)
            .code(code)
            .message("Message")
            .header("Content-Type", contentType)
            .body(body.toResponseBody(contentType.toMediaType()))
            .build()

    /** A track as NewPipeExtractor's YouTube code builds one, with its link for [lang]. */
    private fun subtitlesStream(lang: String, isAutoGenerated: Boolean, extra: String = "") =
        SubtitlesStream.Builder()
            .setContent(timedTextLink(lang, extra), true)
            .setMediaFormat(MediaFormat.TTML)
            .setLanguageCode(lang)
            .setAutoGenerated(isAutoGenerated)
            .build()

    private companion object {
        const val XML = "text/xml; charset=UTF-8"
        const val HTML = "text/html; charset=UTF-8"
        const val PLAIN_TEXT = "text/plain; charset=UTF-8"
    }
}
