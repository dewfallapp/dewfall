package io.github.dewfallapp.core.youtube.newpipe.saved

import io.github.dewfallapp.core.model.SubtitleLine
import io.github.dewfallapp.core.model.VideoId
import io.github.dewfallapp.core.model.YouTubeError
import io.github.dewfallapp.core.model.YouTubeResult
import io.github.dewfallapp.core.youtube.newpipe.recordingLogger
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue
import kotlin.time.Duration.Companion.milliseconds
import kotlinx.coroutines.test.StandardTestDispatcher
import kotlinx.coroutines.test.TestScope
import kotlinx.coroutines.test.runTest
import okhttp3.HttpUrl.Companion.toHttpUrl

/**
 * Tests YouTube's real answers about subtitles: the tracks of "Me at the zoo", Tears of Steel, a
 * video with AI-dubbed audio and Big Buck Bunny, the lines of written and auto-generated tracks,
 * and the videos that can't be played. Listing a video's tracks sends the requests of its page, so
 * the sets of video details serve here too.
 */
class SubtitlesReplayTest {
    private val lines = mutableListOf<String>()

    @Test
    fun `Me at the zoo has two written tracks, in English and German, with TTML links`() = runTest {
        val youTube = savedYouTube(SavedSet.SUBTITLES_ME_AT_THE_ZOO)

        val subtitles = youTube.call(SavedSet.SUBTITLES_ME_AT_THE_ZOO.call).valueOrFail()

        val tracks = (subtitles as VideoSubtitles).tracks
        assertEquals(
            listOf("en" to false, "de" to false),
            tracks.map { it.languageTag to it.isAutoGenerated },
        )
        for (track in tracks) {
            assertEquals(VideoId(ME_AT_THE_ZOO_ID), track.videoId)
            val link = track.url.toHttpUrl()
            assertEquals("www.youtube.com", link.host)
            assertEquals("/api/timedtext", link.encodedPath)
            assertEquals("ttml", link.queryParameter("fmt"))
            // NewPipeExtractor asks for YouTube's own tracks, never a machine translation.
            assertEquals(null, link.queryParameter("tlang"))
        }
        assertEquals(SavedSet.SUBTITLES_ME_AT_THE_ZOO.requests, youTube.sentRequests)
        assertEquals(emptyList(), lines)
    }

    @Test
    fun `Me at the zoo's English lines keep YouTube's times, with plain text`() = runTest {
        val subtitles = callSet(SavedSet.SUBTITLES_ME_AT_THE_ZOO)

        val english = subtitles.linesOf("en", isAutoGenerated = false)

        assertEquals(
            listOf(
                line(1200, 3360, "All right, so here we are, in front of the\nelephants"),
                line(5318, 7974, "the cool thing about these guys is that they\nhave really..."),
                line(7974, 12616, "really really long trunks"),
                line(12616, 14367, "and that's cool"),
                line(14421, 15733, "(baaaaaaaaaaahhh!!)"),
                line(16881, 18881, "and that's pretty much all there is to\nsay"),
            ),
            english,
        )
    }

    @Test
    fun `Me at the zoo's German lines keep their letters outside ASCII`() = runTest {
        val subtitles = callSet(SavedSet.SUBTITLES_ME_AT_THE_ZOO)

        val german = subtitles.linesOf("de", isAutoGenerated = false)

        assertEquals(4, german.size)
        assertEquals(
            line(
                5067,
                12467,
                "Das Coole an den Typen ist dass sie sehr, sehr, sehr, lange Rüssel haben.",
            ),
            german[1],
        )
    }

    @Test
    fun `Tears of Steel's codes become BCP 47 tags, Hebrew's iw included`() = runTest {
        val subtitles = callSet(SavedSet.SUBTITLES_TEARS_OF_STEEL)

        val tags = subtitles.tracks.filter { !it.isAutoGenerated }.map { it.languageTag }

        assertEquals(28, tags.size)
        assertTrue("he" in tags, tags.toString())
        assertTrue("iw" !in tags, tags.toString())
        for (tag in listOf("zh-CN", "zh-Hant", "pt-BR", "pt-PT", "es-ES", "no", "en")) {
            assertTrue(tag in tags, tag)
        }
        assertEquals(
            listOf("en"),
            subtitles.tracks.filter { it.isAutoGenerated }.map { it.languageTag },
        )
        assertEquals(SavedSet.SUBTITLES_TEARS_OF_STEEL.requests, youTubeRequests)
        assertEquals(emptyList(), lines)
    }

    @Test
    fun `Tears of Steel's auto-generated lines are clean phrases, with YouTube's times`() =
        runTest {
            val subtitles = callSet(SavedSet.SUBTITLES_TEARS_OF_STEEL)

            val auto = subtitles.linesOf("en", isAutoGenerated = true)

            assertEquals(97, auto.size)
            assertEquals(
                listOf(
                    line(4799, 11320, "we have main engine start 4 3 2"),
                    line(22160, 27760, "1 you're a jerk D look Celia we have to"),
                    line(25800, 29480, "follow our passions you have your"),
                ),
                auto.take(3),
            )
            // YouTube shows two lines of an auto-generated track at once, so a line ends when the
            // line after the next one starts, and the times say so.
            assertTrue(auto[1].end > auto[2].start)
            assertEquals(auto[3].start, auto[1].end)
            for ((previous, next) in auto.zipWithNext()) {
                assertTrue(previous.start <= next.start)
                // No line starts with the last row of the line before it, as WebVTT's rolling
                // cues would.
                val lastRow = previous.text.lines().last()
                assertTrue(
                    lastRow.split(' ').size < 3 || !next.text.lines().first().startsWith(lastRow),
                    next.text,
                )
            }
            for (subtitleLine in auto) {
                assertTrue(subtitleLine.end > subtitleLine.start)
                assertTrue(subtitleLine.end <= TEARS_OF_STEEL_DURATION)
                assertTrue(
                    '<' !in subtitleLine.text && "&#" !in subtitleLine.text,
                    subtitleLine.text,
                )
            }
            assertTrue(auto.any { it.text == "[Music]" })
        }

    @Test
    fun `a video's tracks made from AI-dubbed audio are left out`() = runTest {
        val youTube = savedYouTube(SavedSet.SUBTITLES_AUTO_DUBBED)

        val subtitles = youTube.call(SavedSet.SUBTITLES_AUTO_DUBBED.call).valueOrFail()

        // YouTube listed 22 tracks: one written and one auto-generated in English, the video's
        // language, and 20 auto-generated machine translations, one for each dubbed audio track.
        val tracks = (subtitles as VideoSubtitles).tracks
        assertEquals(
            listOf("en" to false, "en" to true),
            tracks.map { it.languageTag to it.isAutoGenerated },
        )
        assertEquals("gemini", tracks[1].url.toHttpUrl().queryParameter("variant"))
        assertEquals(20, youTube.saved.dubbedTrackLinks())
        assertEquals(SavedSet.SUBTITLES_AUTO_DUBBED.requests, youTube.sentRequests)
        assertEquals(emptyList(), lines)
    }

    @Test
    fun `Big Buck Bunny has no tracks, after the requests of its page`() = runTest {
        val youTube = savedYouTube(SavedSet.VIDEO_BIG_BUCK_BUNNY)

        val result = youTube.call { subtitleTracks(VideoId(BIG_BUCK_BUNNY_ID)) }

        assertEquals(YouTubeResult.Success(emptyList()), result)
        assertEquals(SavedSet.VIDEO_BIG_BUCK_BUNNY.requests, youTube.sentRequests)
        assertEquals(5, youTube.countedRequests)
        assertEquals(emptyList(), lines)
    }

    @Test
    fun `the tracks of a video that can't be played fail as its video details do`() = runTest {
        val cases =
            listOf(
                Triple(SavedSet.VIDEO_PRIVATE, PRIVATE_VIDEO_ID, YouTubeError.PRIVATE),
                Triple(
                    SavedSet.VIDEO_AGE_RESTRICTED,
                    AGE_RESTRICTED_VIDEO_ID,
                    YouTubeError.UNAVAILABLE,
                ),
                Triple(
                    SavedSet.VIDEO_NEVER_EXISTED,
                    NEVER_EXISTED_VIDEO_ID,
                    YouTubeError.UNAVAILABLE,
                ),
            )
        for ((set, videoId, error) in cases) {
            lines.clear()
            val youTube = savedYouTube(set)

            val result = youTube.call { subtitleTracks(VideoId(videoId)) }

            assertEquals(YouTubeResult.Failure(error), result, set.name)
            assertEquals(
                listOf(
                    "WARN Dewfall.YouTube YouTube call failed call=SUBTITLE_TRACKS error=$error",
                ),
                lines,
                set.name,
            )
            assertEquals(set.requests, youTube.sentRequests, set.name)
            assertEquals(2, youTube.countedRequests, set.name)
        }
    }

    /** The requests that the last [callSet] sent. */
    private var youTubeRequests: List<Endpoint> = emptyList()

    /** The subtitles that [set]'s call returns. */
    private suspend fun TestScope.callSet(set: SavedSet): VideoSubtitles {
        val youTube = savedYouTube(set)
        val subtitles = youTube.call(set.call).valueOrFail() as VideoSubtitles
        youTubeRequests = youTube.sentRequests
        return subtitles
    }

    private fun TestScope.savedYouTube(set: SavedSet) =
        SavedYouTube(set, recordingLogger(lines), StandardTestDispatcher(testScheduler))

    /** The lines that the call read of its track in [languageTag], written or auto-generated. */
    private fun VideoSubtitles.linesOf(languageTag: String, isAutoGenerated: Boolean) =
        read
            .single {
                it.track.languageTag == languageTag && it.track.isAutoGenerated == isAutoGenerated
            }
            .lines

    private fun line(startMillis: Int, endMillis: Int, text: String) =
        SubtitleLine(startMillis.milliseconds, endMillis.milliseconds, text)

    /**
     * How many links in the set's answer from the visionOS client are of tracks that YouTube made
     * from dubbed audio, which the call left out.
     */
    private fun SavedSetContent.dubbedTrackLinks(): Int =
        Regex("""api/timedtext\?[^"]*variant=timing-optimized""")
            .findAll(exchanges[1].response.body.replace("\\u0026", "&"))
            .count()
}
