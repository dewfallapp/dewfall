package io.github.dewfallapp.feature.youtubedebug.logic

import io.github.dewfallapp.core.model.SubtitleLine
import io.github.dewfallapp.core.model.SubtitleTrack
import io.github.dewfallapp.core.model.VideoId
import io.github.dewfallapp.core.model.YouTubeError
import io.github.dewfallapp.core.model.YouTubeResult
import io.github.dewfallapp.core.mvi.Next
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.time.Duration.Companion.seconds

private val TEARS_OF_STEEL = VideoId("R6MlUcmOul8")
private val OTHER_VIDEO = VideoId("jNQXAC9IVRw")

private fun track(
    languageTag: String,
    isAutoGenerated: Boolean = false,
    videoId: VideoId = TEARS_OF_STEEL,
) =
    SubtitleTrack(
        videoId,
        languageTag,
        isAutoGenerated,
        url = "https://www.youtube.com/api/timedtext?lang=$languageTag",
    )

private fun line(start: Int, end: Int, text: String = "line") =
    SubtitleLine(start.seconds, end.seconds, text)

/** The reducer's subtitles section: listing the tracks, then reading one track's lines. */
class SubtitlesSectionTest {
    private val tracks = listOf(track("en"), track("he"), track("en", isAutoGenerated = true))

    private fun reduce(state: YouTubeDebugState, intent: YouTubeDebugIntent): YouTubeDebugState {
        val next = YouTubeDebugReducer.reduce(state, intent)
        assertEquals(Next(next.state), next)
        return next.state
    }

    private fun YouTubeDebugState.after(vararg intents: YouTubeDebugIntent): YouTubeDebugState =
        intents.fold(this) { state, intent -> reduce(state, intent) }

    private fun listed(): YouTubeDebugState =
        YouTubeDebugState()
            .after(
                YouTubeDebugIntent.Run(DebugCall.SUBTITLE_TRACKS),
                YouTubeDebugIntent.SubtitleTracksFinished(
                    TEARS_OF_STEEL,
                    YouTubeResult.Success(tracks),
                ),
            )

    @Test
    fun `the section starts with Tears of Steel, and Run lists its tracks`() {
        val state = YouTubeDebugState().after(YouTubeDebugIntent.Run(DebugCall.SUBTITLE_TRACKS))

        assertEquals(CallStatus.Running(TEARS_OF_STEEL), state.subtitleTracks.status)
    }

    @Test
    fun `the listing numbers the tracks in YouTube's order, with no link`() {
        val summary = (listed().subtitleTracks.status as CallStatus.Succeeded).summary

        assertEquals(TEARS_OF_STEEL, summary.videoId)
        assertEquals(
            listOf(TrackLine(1, "en", false), TrackLine(2, "he", false), TrackLine(3, "en", true)),
            summary.tracks,
        )
        assertEquals(2, summary.writtenCount)
        assertEquals(1, summary.autoGeneratedCount)
    }

    @Test
    fun `reading lines picks a track of the listing on screen`() {
        val state = listed().after(YouTubeDebugIntent.ReadLines(3))

        assertEquals(CallStatus.Running(TrackPick(TEARS_OF_STEEL, 3)), state.subtitleLines)
    }

    @Test
    fun `reading lines before a listing, or of a number it doesn't have, does nothing`() {
        assertEquals(
            CallStatus.Idle,
            YouTubeDebugState().after(YouTubeDebugIntent.ReadLines(1)).subtitleLines,
        )
        assertEquals(CallStatus.Idle, listed().after(YouTubeDebugIntent.ReadLines(4)).subtitleLines)
        assertEquals(CallStatus.Idle, listed().after(YouTubeDebugIntent.ReadLines(0)).subtitleLines)
    }

    @Test
    fun `the lines of the track being read are shown`() {
        val pick = TrackPick(TEARS_OF_STEEL, 3)
        val lines = listOf(line(1, 4, "one"), line(3, 6, "two"))

        val state =
            listed()
                .after(
                    YouTubeDebugIntent.ReadLines(3),
                    YouTubeDebugIntent.SubtitleLinesFinished(pick, YouTubeResult.Success(lines)),
                )

        val summary = (state.subtitleLines as CallStatus.Succeeded).summary
        assertEquals(TrackLine(3, "en", true), summary.track)
        assertEquals(2, summary.lineCount)
    }

    @Test
    fun `the lines of another track, or after a cancel, are dropped`() {
        val reading = listed().after(YouTubeDebugIntent.ReadLines(2))
        val otherPick = TrackPick(TEARS_OF_STEEL, 1)
        val answer = YouTubeResult.Success(listOf(line(1, 2)))

        assertEquals(
            reading,
            reading.after(YouTubeDebugIntent.SubtitleLinesFinished(otherPick, answer)),
        )
        val cancelled = reading.after(YouTubeDebugIntent.CancelLines)
        assertEquals(CallStatus.Cancelled, cancelled.subtitleLines)
        assertEquals(
            cancelled,
            cancelled.after(
                YouTubeDebugIntent.SubtitleLinesFinished(TrackPick(TEARS_OF_STEEL, 2), answer),
            ),
        )
    }

    @Test
    fun `a failure to read lines shows its category`() {
        val state =
            listed()
                .after(
                    YouTubeDebugIntent.ReadLines(1),
                    YouTubeDebugIntent.SubtitleLinesFinished(
                        TrackPick(TEARS_OF_STEEL, 1),
                        YouTubeResult.Failure(YouTubeError.UNAVAILABLE),
                    ),
                )

        assertEquals(CallStatus.Failed(YouTubeError.UNAVAILABLE), state.subtitleLines)
    }

    @Test
    fun `a new listing clears the lines, and its picks name its own video`() {
        val read =
            listed()
                .after(
                    YouTubeDebugIntent.ReadLines(1),
                    YouTubeDebugIntent.InputChanged(DebugCall.SUBTITLE_TRACKS, OTHER_VIDEO.value),
                    YouTubeDebugIntent.Run(DebugCall.SUBTITLE_TRACKS),
                )

        assertEquals(CallStatus.Idle, read.subtitleLines)
        val relisted =
            read.after(
                YouTubeDebugIntent.SubtitleTracksFinished(
                    OTHER_VIDEO,
                    YouTubeResult.Success(listOf(track("de", videoId = OTHER_VIDEO))),
                ),
                YouTubeDebugIntent.ReadLines(1),
            )
        assertEquals(CallStatus.Running(TrackPick(OTHER_VIDEO, 1)), relisted.subtitleLines)
    }

    @Test
    fun `a wrong ID lists nothing`() {
        val state =
            YouTubeDebugState()
                .after(
                    YouTubeDebugIntent.InputChanged(DebugCall.SUBTITLE_TRACKS, "@NASA"),
                    YouTubeDebugIntent.Run(DebugCall.SUBTITLE_TRACKS),
                )

        assertEquals(CallStatus.InvalidInput, state.subtitleTracks.status)
    }

    @Test
    fun `the lines' summary counts rows, overlaps and the lines not shown`() {
        val lines =
            List(25) { index -> line(start = index * 2, end = index * 2 + 3, text = "line $index") }
                .mapIndexed { index, subtitleLine ->
                    if (index == 0) subtitleLine.copy(text = "two\nrows") else subtitleLine
                }

        val summary = lines.toSummary(TrackLine(1, "en", isAutoGenerated = true))

        assertEquals(25, summary.lineCount)
        assertEquals(0.seconds, summary.firstStart)
        assertEquals(51.seconds, summary.latestEnd)
        assertEquals(1, summary.multiRowLines)
        assertEquals(24, summary.overlappingLines)
        assertEquals(SHOWN_SUBTITLE_LINES, summary.shownLines.size)
        assertEquals(5, summary.moreLines)
    }

    @Test
    fun `the latest end is the latest of all lines, not the last line's`() {
        val summary = listOf(line(0, 10), line(2, 4)).toSummary(TrackLine(1, "he", false))

        assertEquals(10.seconds, summary.latestEnd)
        assertEquals(1, summary.overlappingLines)
    }

    @Test
    fun `a track with no lines has no times`() {
        val summary = emptyList<SubtitleLine>().toSummary(TrackLine(1, "en", false))

        assertEquals(0, summary.lineCount)
        assertEquals(null, summary.firstStart)
        assertEquals(null, summary.latestEnd)
        assertEquals(0, summary.moreLines)
    }
}
